@app.route("/checkout", methods=["GET", "POST"])
@login_required
def checkout():
    uid = session["user"]["id"]
    conn = db()

    direct_order = (
        request.args.get("direct") == "1"
        or request.form.get("direct") == "1"
    )

    if direct_order:
        buy_data = session.get("buy_now")
        if not buy_data:
            flash("Please select a product first.", "warning")
            return redirect(url_for("index"))

        pid = str(buy_data["product_id"])
        qty = int(buy_data.get("quantity", 1))
        cart_items = {pid: qty}
    else:
        cart_items = session.get("cart", {})

    products, total = [], 0

    for pid, qty in cart_items.items():
        p = conn.execute(
            "SELECT * FROM products WHERE id=?", (pid,)
        ).fetchone()
        if p and int(qty) > 0:
            products.append((p, int(qty)))
            total += p["price"] * int(qty)

    if not products:
        flash("No products available for checkout.", "warning")
        return redirect(url_for("index"))

    if request.method == "POST":
        choice = request.form.get("delivery_choice", "new")
        name = phone = address = ""
        valid_address = True

        if choice != "new":
            saved = conn.execute(
                "SELECT * FROM addresses WHERE id=? AND user_id=?",
                (choice, uid)
            ).fetchone()

            if saved:
                name = saved["full_name"]
                phone = saved["phone"]
                address = (
                    f'{saved["house"]}, {saved["area"]}, {saved["landmark"]}\n'
                    f'{saved["city"]}, {saved["state"]} - {saved["pincode"]}'
                )
            else:
                flash("Please select a valid saved address.", "danger")
                valid_address = False
        else:
            name = request.form.get("full_name", "").strip()
            phone = request.form.get("phone", "").strip()
            pincode = request.form.get("pincode", "").strip()
            house = request.form.get("house", "").strip()
            area = request.form.get("area", "").strip()
            landmark = request.form.get("landmark", "").strip()
            city = request.form.get("city", "").strip()
            state = request.form.get("state", "").strip()
            address_type = request.form.get("address_type", "Home")

            if (
                not all([name, phone, pincode, house, area, city, state])
                or not phone.isdigit() or len(phone) != 10
                or not pincode.isdigit() or len(pincode) != 6
                or address_type not in ("Home", "Work")
            ):
                flash("Please enter valid delivery details.", "danger")
                valid_address = False
            else:
                address = (
                    f"{house}, {area}, {landmark}\n"
                    f"{city}, {state} - {pincode}"
                )

        if valid_address:
            for product, qty in products:
                current = conn.execute(
                    "SELECT stock FROM products WHERE id=?",
                    (product["id"],)
                ).fetchone()
                if not current or qty > current["stock"]:
                    flash(
                        f'{product["name"]} is no longer available in the requested quantity.',
                        "danger"
                    )
                    valid_address = False
                    break

        if valid_address:
            if choice == "new" and request.form.get("save_address") == "yes":
                is_default = 1 if not conn.execute(
                    "SELECT id FROM addresses WHERE user_id=?", (uid,)
                ).fetchone() else 0

                conn.execute(
                    """INSERT INTO addresses
                    (user_id,full_name,phone,pincode,house,area,landmark,
                     city,state,address_type,is_default)
                    VALUES(?,?,?,?,?,?,?,?,?,?,?)""",
                    (uid, name, phone, pincode, house, area, landmark,
                     city, state, address_type, is_default)
                )

            qr_token = secrets.token_urlsafe(32)

            if app.config["DATABASE_URL"]:
                cur = conn.execute(
                    """INSERT INTO orders
                    (user_id,customer_name,phone,address,total,qr_token,status)
                    VALUES(?,?,?,?,?,?,?) RETURNING id""",
                    (uid, name, phone, address, total, qr_token, 'Confirmed')
                )
                oid = cur.fetchone()["id"]
            else:
                cur = conn.execute(
                    """INSERT INTO orders
                    (user_id,customer_name,phone,address,total,qr_token,status)
                    VALUES(?,?,?,?,?,?,?)""",
                    (uid, name, phone, address, total, qr_token, 'Confirmed')
                )
                oid = cur.lastrowid

            for product, qty in products:
                conn.execute(
                    """INSERT INTO order_items
                    (order_id,product_id,product_name,price,quantity)
                    VALUES(?,?,?,?,?)""",
                    (oid, product["id"], product["name"],
                     product["price"], qty)
                )
                conn.execute(
                    "UPDATE products SET stock=stock-? WHERE id=?",
                    (qty, product["id"])
                )

            conn.commit()

            if direct_order:
                session.pop("buy_now", None)
            else:
                session["cart"] = {}

            flash(
                f"Order #{oid} placed successfully. Payment is currently cash on delivery / manual.",
                "success"
            )
            return redirect(url_for("my_orders"))

    saved_addresses = conn.execute(
        "SELECT * FROM addresses WHERE user_id=? ORDER BY is_default DESC,id DESC",
        (uid,)
    ).fetchall()

    return render_template(
        "checkout.html",
        products=products,
        total=total,
        addresses=saved_addresses,
        direct_order=direct_order
    )

